#!/usr/bin/env python3
"""
NinjaOne SentinelOne Removal Script
====================================

Removes SentinelOne as a tracked antivirus product from all NinjaOne policies.

WHAT IT DOES:
  1. Authenticates to the NinjaOne API via OAuth2 client credentials
  2. Lists all policies in the tenant
  3. For each policy, retrieves custom-field conditions (the only list endpoint
     the API exposes for conditions)
  4. Searches for any condition referencing "SentinelOne" (by displayName or conditionName)
  5. Deletes matching conditions via DELETE /v2/policies/{policy_id}/condition/{condition_id}
  6. Optionally decommissions stale offline devices that have SentinelOne installed

WHY THIS SCRIPT EXISTS:
  Rook uses Huntress for EDR, not SentinelOne. SentinelOne was never actually deployed
  to any online device (0 online devices have it installed). 32 devices report it via
  NinjaOne's AV status query, but all are either stale offline devices or ghost entries
  from an old integration. The SentinelOne condition in NinjaOne policies generates
  false alerts (127 CONDITION_SOFTWARE alerts for missing AV) and dashboard noise.

  The NinjaOne MCP server used by Rook is read-only (17 tools, all list/get/query) and
  cannot delete policy conditions. This script calls the NinjaOne REST API directly.

PREREQUISITES:
  - NinjaOne API credentials (client_id + client_secret)
    Generate at: NinjaOne Admin Portal > Administration > API > API Tokens
    Application type: Machine-to-Machine (API Services)
    Scopes: monitoring, management
  - Python 3.10+ with requests (pip install requests)
  - Network access to app.ninjaone.com (US instance) or app.eu.ninjaone.com (EU instance)

USAGE:
  # Set credentials via environment variables:
  export NINJAONE_CLIENT_ID="your_client_id"
  export NINJAONE_CLIENT_SECRET="your_client_secret"
  
  # Dry run (default — shows what WOULD be deleted, makes no changes):
  python3 remove_sentinelone.py
  
  # Actually delete (pass --apply to make changes):
  python3 remove_sentinelone.py --apply
  
  # EU instance:
  python3 remove_sentinelone.py --instance eu
  
  # Also decommission stale offline devices with SentinelOne:
  python3 remove_sentinelone.py --apply --decommission-stale

AUTHOR: Generated by Reign for Rook Advisors
DATE: 2026-10-01
"""

import argparse
import json
import os
import sys
import time
from datetime import datetime, timezone

try:
    import requests
except ImportError:
    print("ERROR: 'requests' module not installed. Run: pip install requests")
    sys.exit(1)


# --- Configuration ---

NINJAONE_INSTANCES = {
    "us": "https://app.ninjaone.com",
    "eu": "https://app.eu.ninjaone.com",
}


def get_auth_token(base_url, client_id, client_secret):
    """Authenticate to NinjaOne API via OAuth2 client credentials flow."""
    token_url = f"{base_url}/ws/oauth/token"
    payload = {
        "grant_type": "client_credentials",
        "client_id": client_id,
        "client_secret": client_secret,
        "scope": "monitoring management",  # need management scope for DELETE
    }
    resp = requests.post(token_url, data=payload, timeout=30)
    if resp.status_code != 200:
        print(f"AUTH FAILED: {resp.status_code} {resp.text}")
        sys.exit(1)
    token_data = resp.json()
    print(f"Authenticated successfully. Token expires in {token_data.get('expires_in', '?')}s")
    print(f"Scopes: {token_data.get('scope', '?')}")
    return token_data["access_token"]


def api_call(base_url, token, method, path, json_body=None):
    """Make an authenticated NinjaOne API call."""
    url = f"{base_url}{path}"
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/json",
    }
    resp = requests.request(method, url, headers=headers, json=json_body, timeout=60)
    if resp.status_code == 204:
        return None
    if resp.status_code not in (200, 201):
        print(f"  API ERROR {resp.status_code}: {resp.text[:500]}")
        return None
    if resp.text:
        return resp.json()
    return None


def list_policies(base_url, token):
    """Get all policies in the tenant."""
    policies = api_call(base_url, token, "GET", "/v2/policies")
    if not policies:
        print("No policies found or API error.")
        return []
    print(f"Found {len(policies)} policies")
    return policies


def list_custom_field_conditions(base_url, token, policy_id):
    """List custom-field conditions for a policy.
    
    NOTE: The NinjaOne API only exposes list endpoints for custom-field and
    windows-event conditions. The SentinelOne AV product condition is a 
    built-in condition type that may NOT appear in this list. However, the
    DELETE endpoint works for ANY condition type if you know the condition_id.
    
    If the SentinelOne condition doesn't appear here, it means it's a built-in
    AV monitoring condition that can only be found via the NinjaOne web portal
    (Policies > [Policy] > Conditions > Antivirus) or via the organization's
    policy configuration.
    """
    conditions = api_call(base_url, token, "GET", f"/v2/policies/{policy_id}/condition/custom-fields")
    return conditions or []


def search_devices_for_sentinelone(base_url, token):
    """Query antivirus status to find devices with SentinelOne installed."""
    av_data = api_call(base_url, token, "GET", "/v2/queries/antivirus-status")
    if not av_data:
        return []
    
    sentinelone_devices = []
    for record in av_data:
        product = record.get("productName", "")
        if "sentinel" in product.lower():
            sentinelone_devices.append(record)
    
    return sentinelone_devices


def delete_condition(base_url, token, policy_id, condition_id):
    """Delete a policy condition."""
    result = api_call(base_url, token, "DELETE", 
                      f"/v2/policies/{policy_id}/condition/{condition_id}")
    return result is not None  # 204 = success (no content)


def decommission_device(base_url, token, device_id):
    """Decommission (remove) a device from NinjaOne."""
    result = api_call(base_url, token, "POST", f"/v2/device/{device_id}/decommission")
    return result is not None


def main():
    parser = argparse.ArgumentParser(
        description="Remove SentinelOne from NinjaOne tracked products"
    )
    parser.add_argument("--instance", choices=["us", "eu"], default="us",
                        help="NinjaOne instance (default: us)")
    parser.add_argument("--apply", action="store_true",
                        help="Actually make changes (default: dry run)")
    parser.add_argument("--decommission-stale", action="store_true",
                        help="Also decommission stale offline devices with SentinelOne")
    parser.add_argument("--client-id", default=os.environ.get("NINJAONE_CLIENT_ID"),
                        help="NinjaOne API client ID (or set NINJAONE_CLIENT_ID env var)")
    parser.add_argument("--client-secret", default=os.environ.get("NINJAONE_CLIENT_SECRET"),
                        help="NinjaOne API client secret (or set NINJAONE_CLIENT_SECRET env var)")
    args = parser.parse_args()

    # --- Validate credentials ---
    if not args.client_id or not args.client_secret:
        print("ERROR: NinjaOne API credentials required.")
        print()
        print("Set environment variables:")
        print("  export NINJAONE_CLIENT_ID='your_client_id'")
        print("  export NINJAONE_CLIENT_SECRET='your_client_secret'")
        print()
        print("Or pass them as arguments:")
        print("  python3 remove_sentinelone.py --client-id ID --client-secret SECRET")
        print()
        print("Get credentials at: NinjaOne Admin Portal > Administration > API > API Tokens")
        print("  Application type: Machine-to-Machine (API Services)")
        print("  Scopes: monitoring, management")
        sys.exit(1)

    base_url = NINJAONE_INSTANCES[args.instance]
    dry_run = not args.apply

    print("=" * 70)
    print("NinjaOne SentinelOne Removal Script")
    print("=" * 70)
    print(f"Instance: {args.instance} ({base_url})")
    print(f"Mode: {'DRY RUN (no changes will be made)' if dry_run else 'APPLY (will make changes!)'}")
    print(f"Timestamp: {datetime.now(timezone.utc).isoformat()}")
    print()

    # --- Authenticate ---
    print("--- Step 1: Authenticating ---")
    token = get_auth_token(base_url, args.client_id, args.client_secret)
    print()

    # --- Find devices with SentinelOne ---
    print("--- Step 2: Finding devices with SentinelOne ---")
    sentinelone_devices = search_devices_for_sentinelone(base_url, token)
    print(f"Found {len(sentinelone_devices)} devices with SentinelOne in AV status")
    for dev in sentinelone_devices[:10]:
        print(f"  Device ID: {dev.get('deviceId')}, Product: {dev.get('productName')}, "
              f"State: {dev.get('productState')}, Definitions: {dev.get('definitionStatus')}")
    if len(sentinelone_devices) > 10:
        print(f"  ... and {len(sentinelone_devices) - 10} more")
    print()

    # --- List all policies ---
    print("--- Step 3: Listing all policies ---")
    policies = list_policies(base_url, token)
    print()

    # --- Search each policy for SentinelOne conditions ---
    print("--- Step 4: Searching policies for SentinelOne conditions ---")
    found_conditions = []
    no_condition_policies = []

    for policy in policies:
        policy_id = policy.get("id")
        policy_name = policy.get("name", "Unknown")
        node_class = policy.get("nodeClass", "Unknown")
        
        # List custom-field conditions for this policy
        conditions = list_custom_field_conditions(base_url, token, policy_id)
        
        sentinelone_conditions = []
        for cond in conditions:
            cond_name = cond.get("conditionName", "")
            display_name = cond.get("displayName", "")
            # Check if this condition references SentinelOne
            if "sentinel" in cond_name.lower() or "sentinel" in display_name.lower():
                sentinelone_conditions.append(cond)
        
        if sentinelone_conditions:
            for cond in sentinelone_conditions:
                found_conditions.append({
                    "policy_id": policy_id,
                    "policy_name": policy_name,
                    "condition_id": cond.get("id"),
                    "condition_name": cond.get("conditionName"),
                    "display_name": cond.get("displayName"),
                    "enabled": cond.get("enabled"),
                    "severity": cond.get("severity"),
                })
                print(f"  FOUND: Policy '{policy_name}' (id={policy_id}, {nodeClass})")
                print(f"    Condition: {cond.get('displayName', cond.get('conditionName'))}")
                print(f"    ID: {cond.get('id')}")
                print(f"    Enabled: {cond.get('enabled')}, Severity: {cond.get('severity')}")
        else:
            no_condition_policies.append(f"  {policy_name} (id={policy_id}, {node_class})")  # noqa: F841

    if not found_conditions:
        print("  No SentinelOne conditions found via custom-fields API endpoint.")
        print()
        print("  IMPORTANT: The SentinelOne AV condition is likely a BUILT-IN condition")
        print("  type (Antivirus > Product Installation Status), not a custom-field condition.")
        print("  The NinjaOne API only exposes list endpoints for custom-field and")
        print("  windows-event conditions, not for built-in AV conditions.")
        print()
        print("  To find the condition ID, you need to:")
        print("  1. Log into the NinjaOne web portal")
        print("  2. Go to Administration > Configuration > Policies")
        print("  3. Open each policy and check Conditions > Antivirus")
        print("  4. Look for a SentinelOne product installation condition")
        print("  5. Note the condition ID from the URL or API inspector")
        print()
        print("  OR: Disable the SentinelOne integration directly in")
        print("  Administration > Configuration > Integrations > Antivirus > SentinelOne")
        print("  This removes SentinelOne as a tracked product across ALL policies.")
        print()
        print("  The DELETE /v2/policies/{policy_id}/condition/{condition_id} endpoint")
        print("  will work once you have the condition_id from the web portal.")
        return

    print(f"\nFound {len(found_conditions)} SentinelOne conditions across {len(set(c['policy_id'] for c in found_conditions))} policies")
    print()

    # --- Delete conditions ---
    if found_conditions:
        print(f"--- Step 5: {'(DRY RUN) ' if dry_run else ''}Deleting SentinelOne conditions ---")
        deleted = 0
        failed = 0
        for cond in found_conditions:
            print(f"  Policy: {cond['policy_name']} (id={cond['policy_id']})")
            print(f"  Condition: {cond['display_name']} (id={cond['condition_id']})")
            if dry_run:
                print(f"  -> Would DELETE /v2/policies/{cond['policy_id']}/condition/{cond['condition_id']}")
            else:
                success = delete_condition(base_url, token, cond['policy_id'], cond['condition_id'])
                if success:
                    print(f"  -> DELETED successfully")
                    deleted += 1
                else:
                    print(f"  -> DELETE FAILED")
                    failed += 1
            print()
        
        if not dry_run:
            print(f"Deleted: {deleted}, Failed: {failed}")

    # --- Optionally decommission stale devices ---
    if args.decommission_stale and sentinelone_devices:
        print(f"\n--- Step 6: {'(DRY RUN) ' if dry_run else ''}Decommissioning stale offline devices ---")
        print("  Checking which SentinelOne devices are stale (offline >90 days)...")
        
        for dev in sentinelone_devices:
            device_id = dev.get("deviceId")
            # Get device details to check last contact
            device = api_call(base_url, token, "GET", f"/v2/device/{device_id}")
            if device:
                last_contact = device.get("lastContact", 0)
                offline = device.get("offline", False)
                system_name = device.get("systemName", "Unknown")
                days_offline = (time.time() - last_contact) / 86400 if last_contact else 0
                
                if offline and days_offline > 90:
                    print(f"  STALE: {system_name} (id={device_id}) - offline {days_offline:.0f} days")
                    if dry_run:
                        print(f"    -> Would decommission device {device_id}")
                    else:
                        success = decommission_device(base_url, token, device_id)
                        if success:
                            print(f"    -> DECOMMISSIONED")
                        else:
                            print(f"    -> DECOMMISSION FAILED")
                else:
                    print(f"  ACTIVE: {system_name} (id={device_id}) - offline={offline}, {days_offline:.0f} days")
    
    print("\n" + "=" * 70)
    if dry_run:
        print("DRY RUN COMPLETE - no changes were made.")
        print("Run with --apply to make actual changes.")
    else:
        print("COMPLETE - changes have been applied.")
    print("=" * 70)


if __name__ == "__main__":
    main()
